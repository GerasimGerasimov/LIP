void TIM1_CC_IRQHandler (void)
{
  if ((TIM1->SR & TIM_FLAG_CC1)&&(TIM1->DIER & TIM_IT_CC1)) TIM1_user_U1();
  
}

void TIM2_IRQHandler(){
  TIM2->SR = 0;
  ++RAM_DATA.counter[0];
}

